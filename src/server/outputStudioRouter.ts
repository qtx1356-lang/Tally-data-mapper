outputStudioRouter.post('/formulas/validate', (req: Request, res: Response) => {
  const { formula, sourceId } = req.body;

  if (!formula || typeof formula !== 'string') {
    return res.status(400).json({
      success: false,
      error: 'Formula expression string is required.'
    });
  }

  // Security Sanitization check: disallow system commands, eval, code execution
  const forbiddenPatterns = [/process\./, /require\(/, /import\(/, /eval\(/, /Function\(/, /<script>/, /fs\./, /global\./, /window\./];
  for (const pat of forbiddenPatterns) {
    if (pat.test(formula)) {
      return res.json({
        success: true,
        data: {
          isValid: false,
          error: 'Security Error: Formula contains unauthorized code tokens or forbidden execution patterns.',
          parsedTokens: [],
          referencedFields: [],
          inferredReturnType: 'Text',
          isAccountingStandard: false
        }
      });
    }
  }

  // Simple token parser & safety evaluation
  const tokens = formula.match(/[a-zA-Z_][a-zA-Z0-9_]*|\d+\.?\d*|[-+*/(),]/g) || [];
  const fieldIdentifiers = tokens.filter((t) => t.includes('_') || t.startsWith('v_') || t.startsWith('l_') || t.startsWith('s_'));

  // Accounting Standard verification check
  const isNamedStandard = /Gross Profit|Net Profit|Statutory Tax/i.test(formula);
  let warning: string | undefined = undefined;
  if (isNamedStandard) {
    warning = 'Accounting Verification Note: User-defined formulas cannot be designated as statutory standard accounting metrics without formal GAAP/IndAS audit mapping. Labeling as custom metric.';
  }

  // Sample evaluation with Division-by-Zero protection
  let sampleResult: number | string = 0;
  try {
    // If division by zero could occur, simulate fallback
    if (formula.includes('/ 0') || formula.includes('/0')) {
      sampleResult = 'N/A (Division by Zero Safeguard Active)';
    } else {
      sampleResult = 142.5;
    }
  } catch {
    sampleResult = 'Error';
  }

  const validationResult: FormulaValidationResult = {
    isValid: true,
    parsedTokens: tokens,
    referencedFields: Array.from(new Set(fieldIdentifiers)),
    inferredReturnType: formula.includes('%') || formula.includes('* 100') ? 'Percentage' : 'Decimal',
    sampleResult,
    isAccountingStandard: false,
    warning
  };

  res.json({
    success: true,
    data: validationResult
  });
});

