outputStudioRouter.post('/copilot/plan', (req: Request, res: Response) => {
  const { prompt } = req.body;

  if (!prompt || typeof prompt !== 'string') {
    return res.status(400).json({ success: false, error: 'Natural language prompt is required.' });
  }

  const p = prompt.toLowerCase();
  let recommendedDataSource = 'Vouchers';
  let recommendedFields = ['v_date', 'v_no', 'v_party', 'v_amount', 'v_net_amt'];
  let suggestedGrouping = ['v_party'];
  let suggestedFilters: { field: string; operator: string; value: string }[] = [];
  let suggestedChartType: any = 'Bar';

  if (p.includes('stock') || p.includes('inventory') || p.includes('sku')) {
    recommendedDataSource = 'Stock Items';
    recommendedFields = ['s_id', 's_name', 's_group', 's_qty_on_hand', 's_standard_cost', 's_selling_price'];
    suggestedGrouping = ['s_group'];
    suggestedChartType = 'Column';
  } else if (p.includes('tax') || p.includes('gst') || p.includes('hsn')) {
    recommendedDataSource = 'GST';
    recommendedFields = ['v_no', 'v_party', 'v_gstin', 'v_amount', 'v_tax_amt'];
    suggestedGrouping = ['v_state'];
    suggestedChartType = 'Pie';
  } else if (p.includes('ledger') || p.includes('trial') || p.includes('balance')) {
    recommendedDataSource = 'Ledgers';
    recommendedFields = ['l_name', 'l_parent', 'l_op_bal', 'l_cl_bal'];
    suggestedGrouping = ['l_parent'];
    suggestedChartType = 'Bar';
  }

  if (p.includes('above') || p.includes('greater than') || p.includes('lakh')) {
    suggestedFilters.push({ field: 'v_amount', operator: '>', value: '100000' });
  }

  const plan: CopilotReportPlan = {
    prompt,
    interpretedIntent: `Construct analytical report from ${recommendedDataSource} catalog grouped by ${suggestedGrouping.join(', ')}.`,
    recommendedDataSource,
    recommendedFields,
    suggestedFilters,
    suggestedGrouping,
    suggestedCalculations: [{ name: 'Tax Impact %', formula: '(v_tax_amt / v_amount) * 100' }],
    suggestedChartType,
    confidence: 0.94,
    readyToGenerate: true
  };

  res.json({
    success: true,
    data: plan
  });
});

