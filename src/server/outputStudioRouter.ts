outputStudioRouter.post('/reports/import-definition', (req: Request, res: Response) => {
  const { reportDefinition } = req.body;

  if (!reportDefinition || !reportDefinition.name) {
    return res.status(400).json({
      success: false,
      error: 'Invalid report definition schema payload.'
    });
  }

  // Check for unsupported fields
  const primarySource = STANDARD_SOURCES_METADATA.find((s) => s.name === reportDefinition.primarySourceId);
  const knownFieldIds = new Set(primarySource?.fields.map((f) => f.fieldId) || []);

  const unsupportedFields: string[] = [];
  if (Array.isArray(reportDefinition.columns)) {
    reportDefinition.columns.forEach((c: any) => {
      if (!knownFieldIds.has(c.fieldId)) {
        unsupportedFields.push(c.fieldId);
      }
    });
  }

  const importedReport: ReportDefinition = {
    ...reportDefinition,
    id: `rep-imp-${Date.now().toString().slice(-4)}`,
    name: `${reportDefinition.name} (Imported)`,
    owner: 'Current User',
    status: unsupportedFields.length > 0 ? 'Unsupported' : 'Draft',
    version: 1,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString()
  };

  savedReports.unshift(importedReport);

  res.json({
    success: true,
    data: importedReport,
    unsupportedFields,
    requiresMigration: unsupportedFields.length > 0
  });
});

